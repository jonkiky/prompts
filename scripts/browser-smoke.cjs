const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('assert');

(async () => {
  fs.mkdirSync('artifacts', {recursive:true});
  const browser = await chromium.launch({headless:true,channel:process.env.HUB_BROWSER_CHANNEL || 'chrome'});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.HUB_LIVE_URL || 'http://127.0.0.1:8765');
  await page.getByRole('button',{name:/Jordan Lee/}).click();
  await page.getByRole('heading',{name:'Expertise, ready to use.'}).waitFor();
  await page.getByRole('link',{name:'CCDI Slide Generation',exact:true}).waitFor();
  await page.screenshot({path:'artifacts/library.png',fullPage:true});
  await page.getByRole('button',{name:/Create skill/}).click();
  await page.getByLabel('Skill name',{exact:true}).fill('Browser workflow verification');
  await page.getByLabel('When should an assistant use this?').fill('Create a concise internal project briefing from provided source notes.');
  await page.getByRole('button',{name:'Create draft',exact:true}).click();
  await page.getByLabel('File editor').waitFor();
  const skillId=await page.evaluate(()=>location.hash.split('/')[1]);
  const editor=page.getByLabel('File editor');
  await editor.fill((await editor.inputValue())+'\nInclude source evidence in the briefing.\n');
  await page.getByRole('button',{name:'Save file',exact:true}).click();
  await page.getByRole('status').filter({hasText:'File saved'}).waitFor();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('Requested audience').selectOption('company');
  await page.getByLabel('Release notes').fill('First browser-verified company briefing workflow.');
  await page.getByLabel('Next review date').fill('2000-01-01');
  await page.getByRole('button',{name:'Save release details'}).click();
  await page.getByRole('status').filter({hasText:'Release details saved'}).waitFor();
  await page.getByRole('button',{name:/Submit for review/}).click();
  await page.getByRole('button',{name:'Submit revision'}).click();
  await page.getByRole('button',{name:'Withdraw to draft'}).waitFor();
  const options=await page.getByLabel('Switch demonstration identity').locator('option').all();
  let reviewer,author;
  for(const option of options){const text=await option.textContent();if(text.includes('Morgan'))reviewer=await option.getAttribute('value');if(text.includes('Jordan'))author=await option.getAttribute('value')}
  await page.getByLabel('Switch demonstration identity').selectOption(reviewer);
  await page.getByRole('button',{name:'Review',exact:true}).click();
  await page.getByLabel('Review comment').fill('Reviewed all instructions, changes and company audience in browser.');
  await page.getByRole('button',{name:'Approve revision'}).click();
  await page.getByRole('status').filter({hasText:'Revision approve'}).waitFor();
  await page.getByLabel('Switch demonstration identity').selectOption(author);
  await page.getByRole('button',{name:'Publish approved release'}).click();
  await page.getByRole('status').filter({hasText:'Revision publish'}).waitFor();
  await page.getByRole('button',{name:'Versions',exact:true}).click();
  await page.getByRole('heading',{name:'Version history'}).waitFor();
  await page.getByRole('link',{name:/Lifecycle/}).click();
  await page.getByLabel('Filter state').selectOption('overdue');
  await page.getByRole('link',{name:'Browser workflow verification',exact:true}).waitFor();
  // Remove only the synthetic fixture created by this check.
  await page.evaluate(async id=>{
    const me=await fetch('/api/me').then(r=>r.json());
    const skill=await fetch('/api/skills/'+id).then(r=>r.json());
    const r=await fetch('/api/skills/'+id+'/actions',{method:'POST',headers:{'Content-Type':'application/json','X-CSRF-Token':me.csrf},body:JSON.stringify({action:'delete',revision:skill.revision})});
    if(!r.ok)throw Error('Could not clean up browser fixture');
  },skillId);
  await page.getByRole('link',{name:/Library/,exact:false}).first().click();
  await page.getByRole('link',{name:'CCDI Slide Generation',exact:true}).click();
  await page.getByLabel('File editor').waitFor();
  await page.screenshot({path:'artifacts/ccdi-workbench.png',fullPage:true});
  await page.getByRole('link',{name:/Connections/}).click();
  await page.getByRole('heading',{name:'Connect the way you work.'}).waitFor();
  assert(await page.getByRole('heading',{name:'Codex',exact:true}).isVisible());
  assert(await page.getByRole('heading',{name:'Cursor',exact:true}).isVisible());
  assert(await page.getByRole('heading',{name:'GitHub Copilot in VS Code',exact:true}).isVisible());
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/mobile-connections.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth), 'Mobile page overflows horizontally');
  assert.deepStrictEqual(errors,[]);
  await browser.close();
  console.log('Browser workflow passed: create, edit, review, approve, publish, CCDI workbench, three client connections and mobile layout.');
})().catch(e=>{console.error(e);process.exit(1)});
